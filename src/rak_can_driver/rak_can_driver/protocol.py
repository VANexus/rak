@dataclass(frozen=True)
class ChassisVelCmd:
    vx_mm_s: int
    vy_mm_s: int
    wz_mrad_s: int
    enable: bool = True
    speed_limit_low: bool = False

    def encode(self, counter: int = 0) -> bytes:
        flags = (1 if self.enable else 0) | (2 if self.speed_limit_low else 0)
        return build_frame(
            0x100,
            dict(vx_mm_s=self.vx_mm_s, vy_mm_s=self.vy_mm_s, wz_mrad_s=self.wz_mrad_s),
            counter, flags,
        )


@dataclass(frozen=True)
class ChassisVelFb:
    vx_mm_s: int
    vy_mm_s: int
    wz_mrad_s: int
    mode: int           # 0 IDLE, 1 REMOTE, 2 ESTOP, 3 FAULT
    estop_latched: bool = False
    fault_active: bool = False

    @classmethod
    def decode(cls, frame: bytes) -> "ChassisVelFb":
        d = decode_frame(0x200, frame)
        flags = d["_flags"]
        return cls(
            vx_mm_s=d["vx_mm_s"],
            vy_mm_s=d["vy_mm_s"],
            wz_mrad_s=d["wz_mrad_s"],
            mode=(flags >> 0) & 0x3,
            estop_latched=bool((flags >> 2) & 0x1),
            fault_active=bool((flags >> 3) & 0x1),
        )


@dataclass(frozen=True)
class ChassisDiag:
    battery_mv: int
    fault_code: int
    state_bits: int

    @classmethod
    def decode(cls, frame: bytes) -> "ChassisDiag":
        d = decode_frame(0x201, frame)
        return cls(
            battery_mv=d["battery_mv"],
            fault_code=d["fault_code"],
            state_bits=d["state_bits"],
        )


@dataclass(frozen=True)
class SafetyCmd:
    cmd_code: int  # 1..9 per PROTOCOL.md §7.1
    counter: int = 0

    def encode(self) -> bytes:
        return build_frame(0x010, dict(cmd_code=self.cmd_code), self.counter, 0)


