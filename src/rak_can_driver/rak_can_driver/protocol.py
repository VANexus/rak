"""CAN v3 protocol codec — ported from vehical_rak_chassis/tools/can_check.py.

Authoritative spec: docs/PROTOCOL.md in the chassis repo, plus
docs/protocol-signals.yaml (machine-readable signal database).

Byte layout (every frame, 8 bytes):
  [0..5]   signals, packed little-endian, 16-bit each (3 signals × 2 bytes)
  [6]      high nibble = alive counter (0..15), low nibble = flags
  [7]      CRC-8 (poly 0x07, no reflection, no final xor) over [0..6]
           initial value = data_id (per-frame constant)
Byte order: little-endian.

This module is byte-compatible with the C reference generated by
vehical_rak_chassis/tools/can_check.py --c-header.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

PROTOCOL_VERSION = 3

# CRC-8 / ATM-style
CRC8_POLY = 0x07


def crc8(data: bytes, data_id: int) -> int:
    """CRC-8/ATM: poly 0x07, no reflection, no final xor, init = data_id."""
    crc = data_id & 0xFF
    for byte in data:
        crc ^= byte
        for _ in range(8):
            if crc & 0x80:
                crc = ((crc << 1) ^ CRC8_POLY) & 0xFF
            else:
                crc = (crc << 1) & 0xFF
    return crc


