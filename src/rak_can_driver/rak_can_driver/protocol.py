# ---------------------------------------------------------------------------
# Signalling: 16-bit signed/unsigned little-endian, except 8-bit for PROTO_VER
# ---------------------------------------------------------------------------

def _pack_i16(value: int) -> bytes:
    if not -0x8000 <= value <= 0x7FFF:
        raise OverflowError(f"int16 overflow: {value}")
    return value.to_bytes(2, "little", signed=True)


def _pack_u16(value: int) -> bytes:
    if not 0 <= value <= 0xFFFF:
        raise OverflowError(f"uint16 overflow: {value}")
    return value.to_bytes(2, "little", signed=False)


def _pack_u8(value: int) -> bytes:
    if not 0 <= value <= 0xFF:
        raise OverflowError(f"uint8 overflow: {value}")
    return bytes((value,))


def _unpack_i16(buf: bytes, offset: int) -> int:
    return int.from_bytes(buf[offset:offset + 2], "little", signed=True)


def _unpack_u16(buf: bytes, offset: int) -> int:
    return int.from_bytes(buf[offset:offset + 2], "little", signed=False)


def _unpack_u8(buf: bytes, offset: int) -> int:
    return buf[offset]


def _pack_signal(name: str, value: int) -> bytes:
    """Pack one 16-bit signal. PROTO_VER + HW_REV are stored as 8-bit each in a packed u16."""
    if name == "proto_hw_packed":
        # lower byte = PROTO_VER, upper byte = HW_REV
        if not 0 <= value <= 0xFFFF:
            raise OverflowError(f"proto_hw_packed overflow: {value}")
        return value.to_bytes(2, "little", signed=False)
    if name in ("vx_mm_s", "vy_mm_s", "wz_mrad_s",
                "j1_pos_deg", "j2_pos_deg", "j3_pos_deg", "j4_pos_deg"):
        return _pack_i16(value)
    if name in ("base_pos_deg", "battery_mv", "fault_code", "fault_aux",
                "state_bits", "build_hash", "cmd_code"):
        return _pack_u16(value)
    if name in ("rsvd16", "rsvd16_2"):
        return _pack_u16(0)
    raise KeyError(f"unknown signal name: {name}")


def _unpack_signal(name: str, buf: bytes, offset: int) -> int:
    if name == "proto_hw_packed":
        return _unpack_u16(buf, offset)
    if name in ("vx_mm_s", "vy_mm_s", "wz_mrad_s",
                "j1_pos_deg", "j2_pos_deg", "j3_pos_deg", "j4_pos_deg"):
        return _unpack_i16(buf, offset)
    if name in ("base_pos_deg", "battery_mv", "fault_code", "fault_aux",
                "state_bits", "build_hash", "cmd_code"):
        return _unpack_u16(buf, offset)
    if name in ("rsvd16", "rsvd16_2"):
        return _unpack_u16(buf, offset)  # always 0
    raise KeyError(f"unknown signal name: {name}")


# ---------------------------------------------------------------------------
# Frame build / parse
# ---------------------------------------------------------------------------

def build_frame(can_id: int, values: dict, counter: int, flags: int) -> bytes:
    """Pack 8-byte CAN v3 frame.

    can_id : 11-bit arbitration ID (0x000..0x7FF)
    values : dict mapping signal name -> integer physical/raw value
             (only the three signals defined for the message; rsvd16
             is auto-filled with 0)
    counter: 0..15 alive counter; wraps with the 4-bit mask
    flags   : 0..15 flag nibble (enable / mode / etc. depending on the frame)
    """
    if can_id not in MSG_BY_ID:
        raise KeyError(f"unknown CAN id 0x{can_id:03x}")
    msg = MSG_BY_ID[can_id]
    if not 0 <= counter <= 15:
        raise OverflowError(f"counter must fit 4 bits: {counter}")
    if not 0 <= flags <= 15:
        raise OverflowError(f"flags must fit 4 bits: {flags}")
    body = bytearray()
    for name in msg["signals"]:
        body += _pack_signal(name, int(values.get(name, 0)))
    if len(body) != 6:
        raise AssertionError(
            f"{msg['name']} signals packed to {len(body)} bytes, expected 6"
        )
    body.append(((counter & 0xF) << 4) | (flags & 0xF))
    body.append(crc8(bytes(body), msg["data_id"]))
    return bytes(body)


def decode_frame(can_id: int, frame: bytes) -> dict:
    """Parse an 8-byte CAN v3 frame. Returns dict of signal values + counter + flags."""
    if can_id not in MSG_BY_ID:
        raise KeyError(f"unknown CAN id 0x{can_id:03x}")
    if len(frame) != 8:
        raise ValueError(f"frame must be 8 bytes, got {len(frame)}")
    msg = MSG_BY_ID[can_id]
    expected_crc = crc8(frame[:7], msg["data_id"])
    if expected_crc != frame[7]:
        raise ValueError(
            f"CRC mismatch on {msg['name']} (id 0x{can_id:03x}): "
            f"want 0x{expected_crc:02x}, got 0x{frame[7]:02x}"
        )
    out: dict = {}
    offset = 0
    for name in msg["signals"]:
        out[name] = _unpack_signal(name, frame, offset)
        offset += 2
    out["_counter"] = (frame[6] >> 4) & 0xF
    out["_flags"] = frame[6] & 0xF
    out["_crc"] = frame[7]
    return out


