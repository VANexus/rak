# Convenience: physical <-> raw conversion factors (PROTOCOL.md §5)
FACTOR_VX_VY_MM_S = 1              # already mm/s
FACTOR_WZ_MRAD_S = 1              # already mrad/s
FACTOR_DEG = 0.01
FACTOR_BAT_MV = 1                 # already mV


def m_s_to_mm_s(m_per_s: float) -> int:
    return int(round(m_per_s * 1000))


def rad_s_to_mrad_s(rad_per_s: float) -> int:
    return int(round(rad_per_s * 1000))


def mm_s_to_m_s(mm_per_s: int) -> float:
    return mm_per_s / 1000.0


def mrad_s_to_rad_s(mrad_per_s: int) -> float:
    return mrad_per_s / 1000.0


def deg_to_raw(deg_value: float) -> int:
    """0.01 deg/unit -> raw int16 (signed, for joint angles +/-327.67 deg)."""
    raw = int(round(deg_value / FACTOR_DEG))
    return max(-0x8000, min(0x7FFF, raw))


def deg_to_raw_u16(deg_value: float) -> int:
    """0.01 deg/unit -> raw uint16 (0..655.35 deg, for BASE_POS continuous rotation)."""
    raw = int(round(deg_value / FACTOR_DEG))
    return max(0, min(0xFFFF, raw))


def raw_to_deg(raw: int) -> float:
    """raw int16 -> deg."""
    if raw >= 0x8000:
        raw -= 0x10000
    return raw * FACTOR_DEG


def raw_to_deg_u16(raw: int) -> float:
    """raw uint16 -> deg (no sign extension needed)."""
    return raw * FACTOR_DEG


def battery_to_volts(mv: int) -> float:
    return mv / 1000.0
